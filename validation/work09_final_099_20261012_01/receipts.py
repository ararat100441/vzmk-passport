from common import *
def digest(v):return hashlib.sha256(json.dumps(v,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode('utf8')).hexdigest()
e=read(OUT/'EXE_E2E_FINAL.json');d=read(e['evidence']);rows=[]
for p in e['manifests']:
    m=read(p);assert m['seal']==digest({k:v for k,v in m.items() if k!='seal'})
    assert m['quality_validation']['status']=='PASS' and all(v is True for k,v in m['quality_validation'].items() if k!='status')
    assert sha(m['native_quality']['evidence'])==m['native_quality']['evidence_sha256']
    assert all(sha(p)==h for p,h in m['inputs'].items())
    rows.append({'manifest':p,'manifest_sha256':sha(p),'seal_valid':True,'input_hashes_valid':True,'quality_validation_valid':True,'native_quality_evidence_SHA_valid':True,'separate_per_document_Stage7_receipts_produced':False})
closure=[]
for key in ('fixture_closed','fixture_restored'):
    sb=Path(d[key]['sandbox']);request=read(d[key]['request'])
    refs=[request[k] for k in ('shipment','requirements','control')]+request['documents']
    assert all(sha(r['path'])==r['sha256'] for r in refs)
    assert request['official_issue'] is False and request['test_only'] is True and request['passport']=='8001/2099'
    states=[];previous=None
    for i,p in enumerate(sorted((sb/'journal').glob('*.json'))):
        ev=read(p);assert ev['seal']==digest({k:v for k,v in ev.items() if k!='seal'}) and ev['previous']==previous and ev['sequence']==i
        previous=sha(p);states.append(ev['state'])
    assert states.count('COMMITTED')==(1 if key=='fixture_closed' else 0)
    closure.append({'sandbox':str(sb),'sealed_request_bindings':len(refs),'TEST_only':True,'journal_states':states,'journal_hash_chain_valid':True,'COMMITTED_count':states.count('COMMITTED')})
save(OUT/'MANIFEST_AND_TRANSACTION_RECORDS_AUDIT.json',{'status':'PASS','manifests':rows,'closure_records':closure,'separate_Stage7_receipt_chain':'Stage9 uses its own sealed TEST manifest; no separate per-document Stage7 receipt files are generated by this path, so they are not claimed as verified.'})
print('Codex manifest seals, input hashes, native evidence and TEST journal chains PASS',flush=True)
